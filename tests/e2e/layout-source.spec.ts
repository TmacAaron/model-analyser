import {expect,test} from '@playwright/test';
import {randomUUID} from 'node:crypto';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {NodeId,StorageId,QuantizedStorageSpec} from '@model-analyser/contracts';
import {makeLocalGemmProject} from '../../scripts/local-gemm-project.js';
import {c01Project} from '../model-fixtures.js';

test('opens the tail shard and packed storage from its actual bindings and exports the device allocation',async({page})=>{
 const project=makeLocalGemmProject(c01Project()),scenario=project.scenarios[0]!;
 project.projectId=randomUUID();
 scenario.bindings=[{parameterKey:'N',value:{kind:'integer',value:9}}];
 for(const assignment of scenario.parallelPlan.assignments)for(const tensor of assignment.tensorDistributions)if(tensor.distribution.kind==='sharded')tensor.distribution.policy={kind:'padded'};
 scenario.quantizationOverrides=[{selector:{kind:'subtree',rootNodeId:NodeId.parse('$model')},storageIds:[StorageId.parse('sY')],
  activation:QuantizedStorageSpec.parse({payloadBits:4,packingUnitElements:6,alignmentBytes:16,auxiliaries:[{name:'scale',dtype:{category:'float',bits:16,format:'fp16'},count:{kind:'group',groupSize:8}}]})}];
 await page.goto('/');
 await page.getByLabel('导入模型工作区',{exact:true}).setInputFiles({name:'layout-source.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(project))});
 await expect(page.locator('.model-studio')).toHaveAttribute('data-workspace-id',project.projectId);
 await expect(page.locator('.studio-save')).toContainText('已保存 · 修订 1');
 await page.getByRole('button',{name:'分析此配置 ↗',exact:true}).click();
 await expect(page.locator('.analysis-cards')).toBeVisible();
 const inspector=page.locator('.cost-source-inspector');
 await inspector.locator(':scope > summary').click();
 await inspector.getByLabel('成本来源范围',{exact:true}).selectOption({label:'局部 module/op / gpu1'});
 await inspector.getByLabel('成本来源指标',{exact:true}).selectOption('useful:0');
 const local=inspector.getByRole('region',{name:'逐卡运算来源'});
 await local.getByRole('button',{name:'复核此设备的局部方程',exact:true}).click();
 const tensor=local.locator('article').filter({has:page.getByRole('heading',{name:'nl = 4 count',exact:true})}).getByRole('region',{name:'逐卡张量布局推导'});
 await tensor.getByRole('button',{name:'复核此卡的张量布局',exact:true}).click();
 await expect(tensor).toContainText('已复核 16 个有效元素 · 20 个分配元素');
 await expect(tensor).toContainText('每卡分配 ceil(9 ÷ 2) = 5');
 await expect(tensor).toContainText('[5, 9) · 有效 4 · 分配 5');
 const storage=local.locator('article').filter({has:page.getByRole('heading',{name:'yBytes = 22 byte',exact:true})}).getByRole('region',{name:'逐卡分配推导'});
 await storage.getByRole('button',{name:'复核此卡的分配推导',exact:true}).click();
 await expect(storage).toContainText('已复核分配 22 byte');
 await expect(storage).toContainText('ceil(20 ÷ 8) = 3 count');
 await expect(storage).toContainText('16 + 6 = 22 byte');
 const download=page.waitForEvent('download');
 await storage.getByRole('button',{name:'导出此页布局来源',exact:true}).click();
 const file=await(await download).path();
 if(!file)throw Error('Missing layout proof');
 const cli=await promisify(execFile)(process.execPath,['--import','tsx','scripts/verify-leaf-cost-source.ts',file]);
 expect(JSON.parse(cli.stdout)).toMatchObject({kind:'layout_source',selector:{kind:'storage',storageId:'sY',deviceId:'gpu1'},totalBytes:22,perCopyBytes:22});
 await inspector.getByLabel('成本来源范围',{exact:true}).selectOption('storage:sY');
 await inspector.getByLabel('成本来源指标',{exact:true}).selectOption('gpu1');
 const direct=inspector.getByRole('region',{name:'逐卡分配推导'});
 await direct.getByRole('button',{name:'复核此卡的分配推导',exact:true}).click();
 await expect(direct).toContainText('已复核分配 22 byte');
});
